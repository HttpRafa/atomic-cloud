//! The local plugin starts servers as child processes on the controller's
//! machine.
//!
//! It is a wasmite plugin: every exported function runs on a fresh instance,
//! so nothing is kept in memory between calls. Node, server, port and
//! template state lives in the host kv store (see [`state`]) and the server
//! processes are owned by the host (see the `process` interface).

use generated::{
    atomic::plugin_system::{
        errors::{Error, ScopedError},
        types::{Address, Capabilities, Features, Information, Server, ServerProposal},
    },
    export,
    exports::atomic::plugin_system::{lifecycle, node},
};

mod config;
mod log;
mod ports;
mod server;
mod state;
mod storage;
mod template;

#[allow(clippy::all, clippy::pedantic)]
pub mod generated {
    use wit_bindgen::generate;

    generate!({
        world: "plugin",
        path: "../../protocol/wasmite/",
    });
}

// Include the build information generated by build.rs
include!(concat!(env!("OUT_DIR"), "/build_info.rs"));

pub const AUTHORS: [&str; 1] = ["HttpRafa"];

struct Export;

impl lifecycle::Guest for Export {
    fn init(_cloud_identifier: String) -> Result<Information, Error> {
        // Processes do not survive a controller restart (the host kills the
        // ones it finds), so state from a previous run is stale.
        server::reset()?;
        config::Config::parse()?;
        template::prepare_all()?;

        Ok(Information {
            authors: AUTHORS.iter().map(ToString::to_string).collect(),
            version: VERSION.to_string(),
            features: Features::NODE,
        })
    }

    fn tick(_cloud_identifier: String) -> Result<(), Vec<ScopedError>> {
        template::tick()
    }

    fn shutdown(_cloud_identifier: String) -> Result<(), Vec<ScopedError>> {
        // The host kills every remaining process when the plugin is unloaded.
        Ok(())
    }
}

impl node::Guest for Export {
    fn init(node: String, _capabilities: Capabilities, controller: String) -> Result<(), Error> {
        state::put(
            &state::node_key(&node),
            &state::NodeRecord {
                controller: controller.clone(),
            },
        )?;
        info!("Initialized node {}", node);
        Ok(())
    }

    fn tick(node: String) -> Result<(), Vec<ScopedError>> {
        let config = config::Config::parse().map_err(|error| {
            vec![ScopedError {
                scope: node.clone(),
                message: error.to_string(),
            }]
        })?;
        server::tick(&node, &config)
    }

    fn allocate(_node: String, server: ServerProposal) -> Result<Vec<Address>, Error> {
        let config = config::Config::parse()?;
        Ok(ports::allocate(
            &config,
            &server.name,
            server.resources.ports,
        )?)
    }

    fn free(_node: String, addresses: Vec<Address>) -> Result<(), Error> {
        Ok(ports::free(&addresses)?)
    }

    fn start(node: String, server: Server) -> Result<Option<String>, Error> {
        Ok(Some(server::start(&node, &server)?))
    }

    fn restart(node: String, server: Server) -> Result<(), Error> {
        Ok(server::restart(&node, &server)?)
    }

    fn stop(node: String, server: Server) -> Result<(), Error> {
        Ok(server::stop(&node, &server)?)
    }
}

impl From<anyhow::Error> for Error {
    fn from(error: anyhow::Error) -> Self {
        match error.downcast::<Error>() {
            Ok(error) => error,
            Err(error) => Error::Internal(format!("{error:#}")),
        }
    }
}

export!(Export with_types_in generated);
